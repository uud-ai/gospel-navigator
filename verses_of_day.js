// Опорная дата — 1 января 2026, 00:00 UTC. От неё считаем количество
// прошедших календарных дней. UTC, чтобы у пользователей в разных часовых
// поясах смена стиха была хотя бы детерминированной (по полуночи UTC, а не
// по локальному времени).
const VERSE_EPOCH_MS = Date.UTC(2026, 0, 1);
const MS_PER_DAY = 24 * 60 * 60 * 1000;

function getVerseOfDay(now) {
    const today = (now ? now.getTime() : Date.now());
    const dayIndex = Math.floor((today - VERSE_EPOCH_MS) / MS_PER_DAY);
    // На случай, если до опорной даты — берём по модулю с защитой от отрицательных.
    const idx = ((dayIndex % VERSES_OF_DAY.length) + VERSES_OF_DAY.length) % VERSES_OF_DAY.length;
    return {
        ...VERSES_OF_DAY[idx],
        index: idx,
        // Дата в формате YYYY-MM-DD по UTC — стабильный ключ для аналитики
        // и для дневного кэширования, если когда-нибудь понадобится.
        date: new Date(today).toISOString().slice(0, 10)
    };
}
